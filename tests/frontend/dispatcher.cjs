// Current product acceptance: unchanged base, qualitative year, overview; no manual controls.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium, webkit} = require('playwright');
const near = (a,b) => assert.ok(Math.abs(a-b) <= 1e-8 + Math.abs(b)*1e-12, `${a} != ${b}`);
(async () => {
  const baseURL = process.argv[2] || 'http://127.0.0.1:5186';
  assert.equal(new URL(baseURL).hostname, '127.0.0.1');
  const output = process.argv[3] || 'artifacts/submission-final/dispatcher';
  fs.mkdirSync(output, {recursive:true});
  const browser = await (process.env.QA_ENGINE === 'webkit' ? webkit : chromium).launch();
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000}, timezoneId:'America/Los_Angeles', acceptDownloads:true});
    const page = await context.newPage();
    const errors = [], requests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => {if(r.url().endsWith('/query')) requests.push({url:r.url(),body:r.postDataJSON()});});
    const post = async (endpoint, data, expected=200) => {const r=await page.request.post(baseURL+endpoint,{data});assert.equal(r.status(),expected);return r;};
    await page.goto(baseURL);
    await page.getByTestId('total').waitFor();
    const caps=await (await page.request.get(baseURL+'/api/v2/handoff/capabilities')).json();
    const filters={route_ids:['1'],start:caps.start,end:'2025-11-02T00:00:00+03:00',resolution:'hour',forecast_run_id:caps.forecast_run_id};
    const base=await (await post('/api/v2/handoff/query',filters)).json();
    near(Number(await page.getByTestId('total').getAttribute('data-raw-value')),base.total);
    assert.equal(await page.getByLabel('Коэффициент погоды').count(),0);
    assert.equal(await page.getByLabel('Коэффициент события').count(),0);
    assert.equal(await page.locator('.scenario-panel').count(),0);
    await page.getByRole('button',{name:'Таблица',exact:true}).click();
    const displayed=await page.locator('.forecast-table tbody tr td[data-raw-value]').evaluateAll(cells=>cells.map(c=>Number(c.dataset.rawValue)));
    displayed.forEach((v,i)=>near(v,base.rows[i].value));
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'Скачать CSV',exact:true}).click();
    await (await downloadPromise).saveAs(path.join(output,'base-route1.csv'));
    const csv=fs.readFileSync(path.join(output,'base-route1.csv'),'utf8').replace(/^\uFEFF/,'').trim().split(/\r?\n/).map(l=>l.split(','));
    const fields=csv.shift();
    csv.forEach((r,i)=>{near(Number(r[fields.indexOf('value')]),base.rows[i].value);assert.equal(r[fields.indexOf('result_id')],base.result_id);});
    await page.getByRole('button',{name:'1 мес',exact:true}).click(); await page.getByTestId('total').waitFor();
    const monthTotal=Number(await page.getByTestId('total').getAttribute('data-raw-value'));
    const beforeYear=requests.length;
    await page.getByRole('button',{name:'Год · качественно',exact:true}).click();
    await page.getByRole('region',{name:'Качественный год'}).waitFor();
    assert.equal(await page.getByLabel('Маршрут',{exact:true}).inputValue(),'1');
    assert.match(await page.getByTestId('year-period').textContent(),/2025.*2026/);
    assert.equal(await page.getByTestId('total').count(),0);
    assert.equal(await page.getByRole('button',{name:'Скачать CSV',exact:true}).isDisabled(),true);
    assert.equal(requests.length,beforeYear);
    await page.screenshot({path:path.join(output,'year.png'),fullPage:true});
    await page.getByLabel('Маршрут',{exact:true}).selectOption('5'); assert.match(await page.getByRole('region',{name:'Качественный год'}).textContent(),/baseline/);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('2'); assert.match(await page.getByRole('region',{name:'Качественный год'}).textContent(),/только на схеме/);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('1');
    await page.getByRole('button',{name:'1 мес',exact:true}).click(); await page.getByTestId('total').waitFor();
    near(Number(await page.getByTestId('total').getAttribute('data-raw-value')),monthTotal);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('__overview__');
    await page.locator('[data-overview-route="1"]').waitFor();
    const overview=await (await post('/api/v2/handoff/query',{...filters,route_ids:caps.routes.map(r=>r.route_id),end:'2025-12-01T00:00:00+03:00',resolution:'day'})).json();
    for(const r of caps.routes){const expected=overview.rows.filter(p=>p.route_id===r.route_id).reduce((s,p)=>s+p.value,0);near(Number(await page.locator(`[data-overview-route="${r.route_id}"] [data-overview-total]`).getAttribute('data-overview-total')),expected);}
    assert.equal(await page.locator('[data-overview-route]').last().getAttribute('data-overview-route'),'5');
    const beforeTick=requests.length;
    await page.getByLabel('Интервал обзора',{exact:true}).selectOption('5');
    assert.equal(requests.length,beforeTick);
    const selected=Number(await page.locator('[data-overview-route="1"] [data-overview-selected]').getAttribute('data-overview-selected'));
    const overviewDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Скачать CSV',exact:true}).click();await (await overviewDownload).saveAs(path.join(output,'overview-month.csv'));
    await page.screenshot({path:path.join(output,'overview.png'),fullPage:true});
    await page.getByRole('button',{name:'№ 1',exact:true}).click(); await page.getByTestId('map-demand').waitFor();
    near(Number(await page.getByTestId('map-demand').getAttribute('data-raw-value')),selected);
    assert.equal(await page.getByLabel('Точка временного ряда').inputValue(),'5');
    await page.getByRole('button',{name:'1 день',exact:true}).click();await page.getByTestId('total').waitFor();
    const noTickNetwork=requests.length;
    await page.getByLabel('Точка временного ряда').focus();await page.keyboard.press('ArrowRight');
    near(Number(await page.getByTestId('map-demand').getAttribute('data-raw-value')),base.rows[1].value);
    assert.equal(requests.length,noTickNetwork);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('5');await page.getByTestId('total').waitFor();
    near(Number(await page.getByTestId('total').getAttribute('data-raw-value')),0);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('2');assert.equal(await page.getByTestId('total').count(),0);
    assert.equal(await page.getByRole('button',{name:'Скачать CSV',exact:true}).isDisabled(),true);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('__overview__');await page.locator('[data-overview-route="1"]').waitFor();
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
    await page.locator('[data-overview-route="1"] button').click();await page.getByTestId('total').waitFor();
    await page.getByRole('button',{name:'График, таблица и сведения'}).click();
    await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
    assert.equal(errors.length,0,errors.join('\n'));
    assert.equal(requests.filter(r=>r.url.includes('/scenarios/')).length,0);
    fs.writeFileSync(path.join(output,'acceptance.json'),JSON.stringify({run:caps.forecast_run_id,base_total:base.total,month_total:monthTotal,selected_day_6:selected,checks:['base API/UI/CSV unchanged','no manual controls or scenario requests','year no numeric requests','baseline and unsupported','multi-route totals and CSV','shared time no network ticks','mobile 390px'],errors},null,2));
    console.log('PASS base/API/UI/CSV, no manual adjustments, qualitative year, overview/time/baseline/mobile');
    await context.close();
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
