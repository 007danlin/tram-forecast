const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium, webkit} = require('playwright');
const {openScenario, applyScenario, closeDialog, setTheme, mobilePane} = require('./ui.cjs');
const near = (a,b) => assert.ok(Math.abs(a-b)<1e-7+Math.abs(b)*1e-12, `${a} != ${b}`);
(async()=>{
  const baseURL=process.argv[2];
  assert.equal(new URL(baseURL).hostname,'127.0.0.1');
  const browser=await (process.env.QA_BROWSER==='webkit'?webkit:chromium).launch();
  try {
    const page=await browser.newPage({viewport:{width:390,height:844},acceptDownloads:true});
    const errors=[], requests=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{if(r.url().endsWith('/query')) requests.push(r);});
    await page.goto(baseURL);await page.getByTestId('total').waitFor();
    const total=async()=>Number(await page.getByTestId('total').getAttribute('data-raw-value'));
    const waitTotal=async value=>page.waitForFunction(expected=>Math.abs(Number(document.querySelector('[data-testid=total]')?.dataset.rawValue)-expected)<1e-7,value);
    const base=await total();
    const labels=['Погода','Перекрытия','Изменения движения','Мероприятия'];
    await openScenario(page);
    for(const label of labels) assert.equal(await page.getByLabel(`Поправка: ${label}`,{exact:true}).inputValue(),'0');
    const beforeDraft=requests.length;
    await page.getByLabel('Поправка: Погода',{exact:true}).fill('10');
    assert.equal(requests.length,beforeDraft,'A draft must not alter the displayed forecast');
    await closeDialog(page);near(await total(),base);
    let multiplier=1;
    for(const label of labels){
      const result=await applyScenario(page,{[label]:10});
      multiplier*=1.1;await waitTotal(base*multiplier);near(result.total,await total());
    }
    await mobilePane(page, 'Прогноз');
    assert.equal(await page.locator('.forecast-card .forecast-chart__legend').count(),1);
    const download=page.waitForEvent('download');await page.getByRole('button',{name:'Скачать CSV',exact:true}).click();
    const file=await (await download).path();
    const lines=fs.readFileSync(file,'utf8').replace(/^\uFEFF/,'').trim().split(/\r?\n/).map(l=>l.split(','));
    const header=lines.shift();near(lines.reduce((sum,row)=>sum+Number(row[header.indexOf('value')]),0),base*multiplier);
    for(const key of ['weather','event','closures','changes']) near(Number(lines[0][header.indexOf(key)]),1.1);
    await page.getByRole('button',{name:'Таблица',exact:true}).click();
    assert.equal(await page.getByRole('columnheader',{name:'Без поправок',exact:true}).count(),1);
    const beforeYear=requests.length;
    await page.getByRole('button',{name:'Открыть меню',exact:true}).click();
    await page.getByRole('button',{name:'На год',exact:true}).click();
    assert.equal(await page.locator('.scenario-panel').count(),0);
    await closeDialog(page);near(await total(),base*multiplier);
    assert.equal(requests.length,beforeYear);
    await openScenario(page);
    for(const label of labels) assert.equal(await page.getByLabel(`Поправка: ${label}`,{exact:true}).inputValue(),'10');
    await page.getByRole('button',{name:'Сбросить поправки',exact:true}).click();
    await page.getByRole('button',{name:'Применить',exact:true}).click();await waitTotal(base);
    await applyScenario(page,{'Перекрытия':20});
    await page.getByLabel('Маршрут',{exact:true}).selectOption('7');await page.getByTestId('total').waitFor();
    await openScenario(page);
    for(const label of labels) assert.equal(await page.getByLabel(`Поправка: ${label}`,{exact:true}).inputValue(),'0');
    await closeDialog(page);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('5');await page.getByTestId('total').waitFor();
    await applyScenario(page,{'Мероприятия':50});await waitTotal(0);near(await total(),0);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
    fs.mkdirSync('artifacts/verification/scenarios',{recursive:true});
    await page.screenshot({path:'artifacts/verification/scenarios/mobile.png',fullPage:true});
    await page.setViewportSize({width:1366,height:900});
    await page.getByLabel('Маршрут',{exact:true}).selectOption('__overview__');
    await page.locator('[data-overview-route="1"]').waitFor();
    const overviewBase=Number(await page.locator('[data-overview-route="1"] [data-overview-total]').getAttribute('data-overview-total'));
    await applyScenario(page,{'Изменения движения':-20});
    await page.waitForFunction(expected=>Math.abs(Number(document.querySelector('[data-overview-route="1"] [data-overview-total]')?.dataset.overviewTotal)-expected)<1e-7,overviewBase*0.8);
    await page.getByLabel('Маршрут',{exact:true}).selectOption('1');await page.getByTestId('total').waitFor();
    await page.route('**/scenarios/query',route=>route.fulfill({status:503,json:{detail:'Unavailable'}}));
    await openScenario(page);await page.getByLabel('Поправка: Погода',{exact:true}).fill('20');
    await page.getByRole('button',{name:'Применить',exact:true}).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByRole('button',{name:'Скачать CSV',exact:true}).isDisabled(),true);
    await page.unroute('**/scenarios/query');
    await page.getByRole('button',{name:'Повторить запрос',exact:true}).click();await waitTotal(base*1.2);
    await setTheme(page,'light');
    await page.screenshot({path:'artifacts/verification/scenarios/desktop-light.png',fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('PASS four factors API/UI/CSV, draft/cancel/apply/reset, baseline, context, year preservation, mobile');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
